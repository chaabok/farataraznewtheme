import { IsBoolean, IsInt, IsOptional, IsString, MaxLength, Min, MinLength } from "class-validator";

/**
 * Project DTOs — Task 147 (درخواست مالک): فرم «تعریف پروژه» در نرم‌افزار
 * «حسابداری» → زیرمنوی «اطلاعات تفصیلی ها».
 *
 * قرارداد فیلدها (عین فرم مالک):
 *   · کد        — اجباری («کد الزامی است») و بنا به فرمان مالک «بصورت سریالی
 *                 و پشت سرهم» تخصیص می‌یابد؛ بنابراین در ارسال اختیاری است:
 *                 خالی ⇒ سرور نخستین عدد بلااستفاده (سریالی) را می‌سازد؛
 *                 پر ⇒ فقط عددِ درستِ همان سری پذیرفته می‌شود (گارد).
 *                 پس از ثبت تغییرناپذیر است.
 *   · عنوان     — اجباری («عنوان الزامی است»)، حداکثر ۱۰۰ نویسه، یکتا در
 *                 نوع تفصیل «پروژه» و همان گره.
 *   · کد تفصیل  — اختیاری در ارسال؛ خالی ⇒ تخصیص خودکار با «متد اختصاصی»
 *                 (detail-code-assignment — Task 146) از بازهٔ شماره شروع/
 *                 شماره پایان نوع تفصیل «پروژه» (کد مرجع ۸)؛ پر ⇒ دستی با
 *                 قوانین عددی/درون‌بازه/یکتا («کد تفصیل الزامی است» در حالت
 *                 دستی).
 *   · توضیحات   — اختیاری، حداکثر ۵۰۰ نویسه.
 *   · فعال      — بولی (پیش‌فرض فرم: تیک فعال).
 */
export class UpsertProjectDto {
  /** کد پروژه — سریالی سرور؛ خالی = تخصیص خودکار نخستین عدد بلااستفاده. */
  @IsOptional()
  @IsString()
  @MaxLength(20)
  code?: string;

  /** عنوان پروژه — اجباری، یکتا در نوع «پروژه» + گره. */
  @IsString()
  @MinLength(1)
  @MaxLength(100)
  title!: string;

  /** کد تفصیل — خالی = تخصیص خودکار از بازهٔ شماره‌گذاری نوع «پروژه». */
  @IsOptional()
  @IsString()
  @MaxLength(20)
  detailCode?: string;

  @IsOptional()
  @IsString()
  @MaxLength(500)
  description?: string;

  @IsBoolean()
  isActive!: boolean;

  /**
   * Task 122 (قرارداد مشترک) — گرهٔ ساختار سازمانی هدف (از OrgScope فرانت).
   * اختیاری: نبودِ آن = دفتر مرکزی. سرور وجود/فعال‌بودنِ گره را کنترل می‌کند.
   */
  @IsOptional()
  @IsInt()
  @Min(1)
  structureId?: number;
}
